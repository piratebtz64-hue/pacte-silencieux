function build(
  prefix: string,
  category: SupportOpening['category'],
  intent: 'offer' | 'seek',
  texts: string[],
  responses: string[]
): SupportOpening[] {
  return texts.map((text, i) => ({
    id: `${prefix}${i + 1}`,
    category,
    intent,
    text,
    responses,
  }));
}

